// Build the macOS Mail-fidelity demo stylesheet: compose() the six mail
// families (plus buttons/page for the chrome bits the demo markup uses) over a
// theme and write mail-macmail.css next to index.html.
//
//   node build.mjs      — after `npm run build` at the repo root, which is
//                         what produces ../../dist/compose.js (browser-safe
//                         ESM, same convention as experiments/browser-qa,
//                         mail-gmail and mail-outlook — and a STALE dist
//                         ships stale component CSS, so rebuild after any
//                         src/ edit).
//
// The generated file is git-ignored; the Mac Mail look itself lives in
// macmail-skin.css as unlayered token overrides — component CSS is never
// edited there (see docs/design/mail-components.md §5c).
import { writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { compose } from '../../dist/compose.js'

const here = dirname(fileURLToPath(import.meta.url))

const css = compose({
  theme: 'nord',
  components: [
    'mail-list', 'mail-thread', 'mail-folder-tree', 'mail-compose',
    'mail-action-bar', 'mail-search', 'buttons', 'page',
  ],
})

const banner = `/* GENERATED by experiments/mail-macmail/build.mjs — do not edit.
   compose() over the sure-ui mail families; the Mac Mail skin is applied
   separately, unlayered, by macmail-skin.css (tokens only). */\n`

const out = banner + css
writeFileSync(join(here, 'mail-macmail.css'), out)
console.log(`mail-macmail.css — ${Buffer.byteLength(out)} bytes`)
