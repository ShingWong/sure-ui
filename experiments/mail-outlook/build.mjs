// Build the Outlook Online-fidelity demo stylesheet: compose() the six mail
// families (plus buttons/page for the chrome bits the demo markup uses) over a
// theme and write mail-outlook.css next to index.html.
//
//   node build.mjs      — after `npm run build` at the repo root, which is
//                         what produces ../../dist/compose.js (browser-safe
//                         ESM, same convention as experiments/browser-qa and
//                         experiments/mail-gmail — and a STALE dist ships
//                         stale component CSS, so rebuild after any src/ edit).
//
// The generated file is git-ignored; the Outlook look itself lives in
// outlook-skin.css as unlayered token overrides — component CSS is never
// edited there (see docs/design/mail-components.md §5b).
import { writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { compose } from '../../dist/compose.js'

const here = dirname(fileURLToPath(import.meta.url))

const css = compose({
  theme: 'nord',
  components: [
    'mail-list', 'mail-thread', 'mail-folder-tree', 'mail-compose',
    'mail-action-bar', 'mail-search', 'buttons', 'page',
  ],
})

const banner = `/* GENERATED by experiments/mail-outlook/build.mjs — do not edit.
   compose() over the sure-ui mail families; the Outlook skin is applied
   separately, unlayered, by outlook-skin.css (tokens only). */\n`

const out = banner + css
writeFileSync(join(here, 'mail-outlook.css'), out)
console.log(`mail-outlook.css — ${Buffer.byteLength(out)} bytes`)
